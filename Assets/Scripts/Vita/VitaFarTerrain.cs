    // The installed settings for the weather now (WeatherManager keeps no "current weather fog" apart from currentOutdoorFogSettings,
    // which still holds the old values right after the install)
    static WeatherManager.FogSettings WeatherFog(WeatherManager weather)
    {
        if (weather.currentOutdoorFogSettings.density >= 0.05f) return weather.HeavyFogSettings;
        if (weather.IsSnowing) return weather.SnowyFogSettings;
        if (weather.IsRaining) return weather.RainyFogSettings;
        if (weather.IsOvercast) return weather.OvercastFogSettings;
        return weather.SunnyFogSettings;
    }

    void LoadFullMode()
    {
        byte[] data;
        try
        {
            data = System.IO.File.ReadAllBytes(System.IO.Path.Combine(System.IO.Path.Combine(Application.streamingAssetsPath, "VitaNative"), "wodfar.bin"));
        }
        catch (System.Exception e)
        {
            Debug.LogWarning("VITAFAR basic mode: wodfar.bin: " + e.Message);
            return;
        }
        int n = System.BitConverter.ToInt32(data, 0), o = 4 + 62500;
        water = new byte[62500];
        System.Buffer.BlockCopy(data, 4, water, 0, 62500);
        liftCells = new int[n];
        lifts = new float[n];
        for (int i = 0; i < n; i++, o += 8)
        {
            liftCells[i] = System.BitConverter.ToInt32(data, o);
            lifts[i] = System.BitConverter.ToSingle(data, o + 4);
        }
    }

    // The reference's full-mode height (GenerateWorldTerrain, InitMountainVisibility): land below the sea is lifted 1 above it so only
    // the deriv map makes water; mountains are lifted only outside the near-terrain cutout (TerrainDistance - 1 + mountainCutoutBuffer 1),
    // (inside it the PC shows World of Daggerfall's mountain models; the Vita has none of those); water cells are lowered back to
    // the sea after the lifts.
    float FullHeight(float h, int x, int y, int px, int py, ITerrainSampler sampler)
    {
        if (h < sampler.OceanElevation)
            h = sampler.OceanElevation + 1f;
        int cut = world.TerrainDistance;
        if (System.Math.Abs(x - px) > cut || System.Math.Abs(y - py) > cut)
        {
            int k = System.Array.BinarySearch(liftCells, y * WoodsFile.mapWidthValue + x);
            if (k >= 0)
                h = Mathf.Max(h, lifts[k] * sampler.MaxTerrainHeight);
        }
        int c = y * WoodsFile.mapWidthValue + x;
        return (water[c >> 3] & 1 << (c & 7)) != 0 ? sampler.OceanElevation : h;
    }

    void OnDestroy()
    {
        Thick = 1f;
        if (mesh != null)
            Destroy(mesh);
        if (material != null)
            Destroy(material);
    }

    void LateUpdate()
    {
        Transform tile = world != null && !GameManager.Instance.IsPlayerInside ? world.GetTerrainTransform(world.MapPixelX, world.MapPixelY) : null;
        if (tile == null || Hidden)
        {
            meshRenderer.enabled = false;
            return;
        }
        float target = VitaCulling.TownRenderersCulled == 0 ? 0f : 1f;
        if (Thick != target)
        {
            // At once right after a load or leaving a building (renderer still off), faded while walking
            Thick = meshRenderer.enabled ? Mathf.MoveTowards(Thick, target, Time.unscaledDeltaTime / FogFadeSeconds) : target;
            GameManager.Instance.WeatherManager.SetFog(WeatherFog(GameManager.Instance.WeatherManager));
            if (Thick == target)
                Debug.LogFormat("VITAFAR fog thick {0} (town renderers cut {1}), fog {2} density {3}", target, VitaCulling.TownRenderersCulled,
                    RenderSettings.fogMode, RenderSettings.fogDensity);
        }
        transform.position = tile.position;
        bool winter = DaggerfallUnity.Instance.WorldTime.Now.SeasonValue == DaggerfallDateTime.Seasons.Winter;
        int tiles = LoadedTiles();
        float sig = HeightSig(tiles);
        if (world.MapPixelX != builtX || world.MapPixelY != builtY || winter != builtWinter || tiles != builtTiles || sig != builtSig)
            Build(world.MapPixelX, world.MapPixelY, winter, tiles);
        meshRenderer.enabled = true;
        SetGlobals();
        material.SetFloat("_VitaFarZTest", OnTop ? 8f : 4f);    // CompareFunction Always / LessEqual (shader defaults aren't applied)
    }

    // Bit per tile of the 3x3 around the player that is loaded as near terrain (the only cells the near grid can cover at
    // TerrainDistance 1, 2x2 or 3x3); a change rebuilds the index list.
    int LoadedTiles()
    {
        int bits = 0;
        for (int y = -1; y <= 1; y++)
            for (int x = -1; x <= 1; x++)
            {
                GameObject go = world.GetTerrainFromPixel(world.MapPixelX + x, world.MapPixelY + y);
                if (go != null && go.activeInHierarchy)
                    bits |= 1 << ((y + 1) * 3 + x + 1);
            }
        return bits;
    }

    // StreamingWorld turns a tile's object on before its heights are written (updateData is still set then), so LiftBorder sampled a
    // reused tile's old heights and nothing rebuilt it once the new ones landed: with World of Daggerfall - Terrain, whose near tiles sit
    // far above the WOODS base, a strip of sky showed along the near edges from above. A few height
    // reads per loaded tile change when its heights do, and rebuild the mesh then.
    float HeightSig(int tiles)
    {
        float sig = 0f;
        for (int ty = -1; ty <= 1; ty++)
            for (int tx = -1; tx <= 1; tx++)
            {
                if (!Loaded(tiles, tx, ty))
                    continue;
                GameObject go = world.GetTerrainFromPixel(world.MapPixelX + tx, world.MapPixelY + ty);
                Terrain terrain = go != null ? go.GetComponent<Terrain>() : null;
                if (terrain == null || terrain.terrainData == null)
                    continue;
                TerrainData data = terrain.terrainData;
                int m = data.heightmapResolution - 1, h = m / 2;
                sig += data.GetHeight(0, 0) + data.GetHeight(m, m) * 3f + data.GetHeight(h, 0) * 5f + data.GetHeight(0, h) * 7f +
                    data.GetHeight(m, h) * 11f + data.GetHeight(h, m) * 13f;
            }
        return sig;
    }

    void Build(int px, int py, bool winter, int tiles)
    {
        float start = Time.realtimeSinceStartup;
        DaggerfallUnity dfUnity = DaggerfallUnity.Instance;
        ITerrainSampler sampler = dfUnity.TerrainSampler;
        WoodsFile woods = dfUnity.ContentReader.WoodsFileReader;
        MapsFile maps = dfUnity.ContentReader.MapFileReader;
        float scale = MapsFile.WorldMapTerrainDim * MeshReader.GlobalScale;
        float yScale = world.TerrainScale;

        for (int j = 0; j < Dim; j++)
            for (int i = 0; i < Dim; i++)
            {
                int x = Mathf.Clamp(px + i - Radius, 0, WoodsFile.mapWidthValue - 1);
                int y = Mathf.Clamp(py + j - Radius, 0, WoodsFile.mapHeightValue - 1);
                float h = woods.GetHeightMapValue(x, y) * sampler.TerrainHeightScale(x, y);
                if (water != null)
                    h = FullHeight(h, x, y, px, py, sampler);
                heights[j * Dim + i] = Mathf.Max(h, sampler.OceanElevation) * yScale;
            }
        LiftBorder(px, py, tiles, scale);

        for (int j = 0; j < Dim; j++)
            for (int i = 0; i < Dim; i++)
            {
                int k = j * Dim + i;
                // The reference puts map pixel (x, y)'s sample at (x - playerX + 1, -(y - playerY)) tiles from the player tile's origin
                verts[k] = new Vector3((i - Radius + 1) * scale, heights[k], -(j - Radius) * scale);
                float hw = heights[j * Dim + Mathf.Max(i - 1, 0)], he = heights[j * Dim + Mathf.Min(i + 1, Dim - 1)];
                float hn = heights[Mathf.Max(j - 1, 0) * Dim + i], hs = heights[Mathf.Min(j + 1, Dim - 1) * Dim + i];
                Vector3 n = new Vector3(hw - he, 2f * scale, hs - hn).normalized;      // +z is north (map y - 1)
                normals[k] = n;
                int x = Mathf.Clamp(px + i - Radius, 0, WoodsFile.mapWidthValue - 1);
                int y = Mathf.Clamp(py + j - Radius, 0, WoodsFile.mapHeightValue - 1);
                // Land colour on every vertex, water picked per pixel (as the reference's per-fragment terrain shader does): blending a
                // water and a land vertex colour over 820 m drew pale land smears across sea channels.
                int climate = maps.GetClimateIndex(x, y);
                colors[k] = GroundColor(climate, false, n.y, winter);
                wet[k] = new Vector2(heights[k] <= sampler.OceanElevation * yScale || climate == 223 ? -1f : 1f, 0f);
            }

        // Cell (i, j) spans the samples i..i+1, j..j+1 = exactly the tile at map pixel (px + i - Radius + 1, py + j - Radius + 1)
        int count = 0;
        for (int j = 0; j < Dim - 1; j++)
            for (int i = 0; i < Dim - 1; i++)
            {
                int tx = i - Radius + 1, ty = j - Radius + 1;
                if (tx >= -1 && tx <= 1 && ty >= -1 && ty <= 1 && (tiles & 1 << ((ty + 1) * 3 + tx + 1)) != 0)
                    continue;
                int a = j * Dim + i, b = a + 1, c = a + Dim, d = c + 1;     // c, d: one row south
                indices[count++] = a; indices[count++] = b; indices[count++] = c;
                indices[count++] = b; indices[count++] = d; indices[count++] = c;
            }
        // Skirts: LiftBorder raises a far edge as one straight line over the near edge's highest point, so on rugged near tiles (World of
        // Daggerfall - Terrain) the far edge stands tens of metres over the rest of the near edge and from above the sky shows under it
        // (the same with far clip 10000 and with the far mesh drawn on top). A wall from the far edge down to
        // the sampled near edge closes that wedge; both faces, since it is seen from either side. Drawn at the far plane like the rest,
        // so near ground always covers it.
        int sv = Dim * Dim;
        float wedge = 0f;
        for (int e = 0; e < edgeCount; e++)
        {
            int v0 = edgeV0[e], v1 = edgeV1[e], first = sv;
            for (int n = 0; n < Samples; n++, sv += 2)
            {
                float t = n / (Samples - 1f);
                Vector3 top = Vector3.Lerp(verts[v0], verts[v1], t);
                verts[sv] = top;
                wedge = Mathf.Max(wedge, Mathf.Abs(top.y - edgeNear[e * Samples + n]));
                float near = edgeNear[e * Samples + n];
                verts[sv + 1] = new Vector3(top.x, near + (near < top.y ? -1f : 1f), top.z);    // 1 m past the near edge: no crack
                normals[sv] = normals[sv + 1] = Vector3.Lerp(normals[v0], normals[v1], t).normalized;
                colors[sv] = colors[sv + 1] = Color32.Lerp(colors[v0], colors[v1], t);
                wet[sv] = wet[sv + 1] = new Vector2(1f, 0f);
            }
            for (int n = 0; n < Samples - 1; n++)
            {
                int a = first + n * 2, b = a + 1, c = a + 2, d = a + 3;     // a, c: top; b, d: bottom
                indices[count++] = a; indices[count++] = c; indices[count++] = b;
                indices[count++] = c; indices[count++] = d; indices[count++] = b;
                indices[count++] = a; indices[count++] = b; indices[count++] = c;
                indices[count++] = c; indices[count++] = b; indices[count++] = d;
            }
        }
        for (; sv < verts.Length; sv++)
            verts[sv] = Vector3.zero;

        int[] tris = new int[count];
        System.Array.Copy(indices, tris, count);

        mesh.Clear();
        mesh.vertices = verts;
        mesh.normals = normals;
        mesh.colors32 = colors;
        mesh.uv = wet;
        mesh.triangles = tris;
        mesh.bounds = new Bounds(Vector3.zero, new Vector3(4000f, 20000f, 4000f));    // around the camera: never culled
        builtX = px; builtY = py; builtWinter = winter; builtTiles = tiles; builtSig = HeightSig(tiles);
        Debug.LogFormat("VITAFAR built at {0},{1}: {2} triangles, winter {3}, near tiles {4}, {5:F1} ms, {6} skirts, widest wedge {7:F1} m", px, py,
            count / 3, winter, System.Convert.ToString(tiles, 2), (Time.realtimeSinceStartup - start) * 1000f, edgeCount, wedge);
    }

    // The near terrain adds two noise layers to the WOODS height (DefaultTerrainSampler: up to tens of metres), so where a loaded tile
    // meets a far cell on a slope the far edge can sit below it and the sky shows through the gap. Each far vertex on such a
    // border is raised just enough to stay over the near-terrain heights sampled along the bordering edges: the far mesh is drawn at the far plane, so where
    // it ends up above the near edge it shows as more hillside, never over near ground.
    void LiftBorder(int px, int py, int tiles, float scale)
    {
        edgeCount = 0;
        for (int k = 0; k < lift.Length; k++)
            lift[k] = float.MinValue;
        for (int ty = -1; ty <= 1; ty++)
            for (int tx = -1; tx <= 1; tx++)
            {
                if (!Loaded(tiles, tx, ty))
                    continue;
                GameObject go = world.GetTerrainFromPixel(px + tx, py + ty);
                Terrain terrain = go != null ? go.GetComponent<Terrain>() : null;
                if (terrain == null || terrain.terrainData == null)
                    continue;
                int i = tx + Radius - 1, j = ty + Radius - 1;             // cell (i, j) = this tile; its corners are vertices i..i+1, j..j+1
                for (int side = 0; side < 4; side++)
                {
                    int nx = tx + (side == 0 ? -1 : side == 1 ? 1 : 0), ny = ty + (side == 2 ? -1 : side == 3 ? 1 : 0);
                    if (Loaded(tiles, nx, ny))
                        continue;
                    int v0 = side == 1 ? j * Dim + i + 1 : side == 3 ? (j + 1) * Dim + i : j * Dim + i;
                    int v1 = side == 0 ? (j + 1) * Dim + i : side == 2 ? j * Dim + i + 1 : (j + 1) * Dim + i + 1;
                    Vector3 a = new Vector3((v0 % Dim - Radius + 1) * scale, 0, -(v0 / Dim - Radius) * scale);
                    Vector3 b = new Vector3((v1 % Dim - Radius + 1) * scale, 0, -(v1 / Dim - Radius) * scale);
                    // Both ends go to the near height at their corner, and the skirt (Build) covers the near edge's rise and fall
                    // between them. Before, the least raise of both ends that kept the straight far edge over the near edge at every
                    // sample was used: on World of Daggerfall - Terrain's rugged edges that stood the far edge up to 275 m over the rest
                    // of the near edge, with the sky under it from above. Raising both ends to the edge's highest point made a slab over the skyline.
                    float raise = 0f, near0 = 0f, near1 = 0f;
                    int e = edgeCount < MaxEdges ? edgeCount++ : -1;
                    for (int n = 0; n < Samples; n++)
                    {
                        float t = n / (Samples - 1f);
                        Vector3 w = transform.position + Vector3.Lerp(a, b, t);
                        float near = terrain.SampleHeight(w) + terrain.transform.position.y - transform.position.y;
                        raise = Mathf.Max(raise, near - Mathf.Lerp(heights[v0], heights[v1], t));
                        if (e >= 0)
                            edgeNear[e * Samples + n] = near;
                        if (n == 0) near0 = near;
                        near1 = near;
                    }
                    if (e >= 0)
                    {
                        edgeV0[e] = v0;
                        edgeV1[e] = v1;
                    }
#if VITA_FAR_RAISE
                    lift[v0] = Mathf.Max(lift[v0], heights[v0] + raise);
                    lift[v1] = Mathf.Max(lift[v1], heights[v1] + raise);
#else
                    lift[v0] = Mathf.Max(lift[v0], near0);     // the same corner seen from two edges: same height
                    lift[v1] = Mathf.Max(lift[v1], near1);
#endif
                }
            }
        for (int k = 0; k < lift.Length; k++)
            if (lift[k] > float.MinValue)
#if VITA_FAR_RAISE
                heights[k] = Mathf.Max(heights[k], lift[k]);    // only ever up: a lowered vertex opens a gap of its own
#else
                heights[k] = lift[k];                           // down too: the skirt closes that gap
#endif
    }

    static bool Loaded(int tiles, int tx, int ty)
    {
        return tx >= -1 && tx <= 1 && ty >= -1 && ty <= 1 && (tiles & 1 << ((ty + 1) * 3 + tx + 1)) != 0;
    }

    // The reference's per-fragment pick (FarTerrainCommon.cginc getColorFromTerrain / sampleLandBiome) with each tile's mean colour
    static Color32 GroundColor(int climate, bool water, float up, bool winter)
    {
        int group;
        if (climate == 224 || climate == 225 || climate == 229) group = 0;          // desert
        else if (climate == 226 || climate == 230) group = 1;                       // mountain
        else if (climate == 227 || climate == 228) group = 3;                       // swamp
        else group = 2;                                                             // woodland (231-233) and ocean
        if (winter && ClimateSwaps.VitaSnowless(climate))
            winter = false;
        Color32[] set = Colors[group * 3 + (winter ? 1 : 0)];
        if (water || climate == 223)
            return Colors[2 * 3 + (winter ? 1 : 0)][0];                            // the reference uses the woodland water tile
        float grass, dirt, stone;
        if (up > CosDirt) { grass = (up - CosDirt) / (1f - CosDirt); dirt = 1f - grass; stone = 0f; }
        else if (up > CosStone) { grass = 0f; dirt = (up - CosStone) / (CosDirt - CosStone); stone = 1f - dirt; }
        else { grass = 0f; dirt = 0f; stone = 1f; }
        return new Color32((byte)(set[2].r * grass + set[1].r * dirt + set[3].r * stone),
            (byte)(set[2].g * grass + set[1].g * dirt + set[3].g * stone),
            (byte)(set[2].b * grass + set[1].b * dirt + set[3].b * stone), 255);
    }

    void SetGlobals()
    {
        if (sun != null && sun.enabled)
        {
            Shader.SetGlobalVector(sunDirId, -sun.transform.forward);
            Shader.SetGlobalColor(sunColorId, sun.color * sun.intensity);
        }
        else
            Shader.SetGlobalColor(sunColorId, Color.black);
        Shader.SetGlobalColor(ambientId, RenderSettings.ambientLight);
        Shader.SetGlobalColor(fogColorId, RenderSettings.fogColor);
        Shader.SetGlobalColor(waterId, GroundColor(231, true, 1f, builtWinter));

        // The fog in effect (the reference's thin weather fog, or the Vita's thick one near towns), in the reference's form (fcolor:
        // exp2(-density * d), linear (end - d) / (end - start + 1)), so the far land is never clearer than the land in front of it.
        // DFU's own sunny fog (linear, gone at 2,400 m) hid the whole mesh. Exponential modes also fade the mesh's own edge
        // (~16 km) into the fog colour over its outer 40%, where the reference had more world.
        Vector4 f;
        if (RenderSettings.fogMode == FogMode.Linear)
        {
            float range = RenderSettings.fogEndDistance - RenderSettings.fogStartDistance + 1f;
            f = new Vector4(0f, 0f, RenderSettings.fogEndDistance / range, -1f / range);
        }
        else
        {
            float end = (Radius - 1) * MapsFile.WorldMapTerrainDim * MeshReader.GlobalScale, range = end * 0.4f, d = RenderSettings.fogDensity;
            f = RenderSettings.fogMode == FogMode.ExponentialSquared ? new Vector4(0f, d * d, end / range, -1f / range) :
                new Vector4(d, 0f, end / range, -1f / range);
        }
        Shader.SetGlobalVector(fogId, f);

        float far = GameManager.Instance.MainCamera.farClipPlane;
        Shader.SetGlobalVector(depthId, new Vector4(far * 0.90f, far * 0.099f, 1f / 6000f, 0f));
    }
